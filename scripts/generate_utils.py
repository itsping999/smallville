#!/usr/bin/env python3
"""Generate reverie/backend_server/utils.py from .env.

The upstream project expects a utils.py with OpenAI settings in the
reverie/backend_server directory.  This script reads .env at the repo
root and writes the generated file so secrets stay out of source control.
"""
from __future__ import annotations

import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENV_FILE = ROOT / ".env"
OUT = ROOT / "reverie" / "backend_server" / "utils.py"


def load_env(path: Path) -> dict[str, str]:
    env: dict[str, str] = {}
    if not path.exists():
        return env
    for raw in path.read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        env[key.strip()] = value.strip().strip('"').strip("'")
    return env


def env_value(env: dict[str, str], key: str, default: str = "") -> str:
    return os.getenv(key) or env.get(key) or default


def main() -> None:
    env = load_env(ENV_FILE)
    api_key = env_value(env, "LLM_API_KEY")
    base_url = env_value(env, "LLM_BASE_URL")
    model = env_value(env, "LLM_MODEL")
    completion_model = env_value(env, "LLM_COMPLETION_MODEL", model) or model
    disable_embeddings = env_value(env, "LLM_DISABLE_EMBEDDINGS", "0")
    embedding_model = env_value(env, "LLM_EMBEDDING_MODEL")
    key_owner = env_value(env, "KEY_OWNER", "local")
    debug = env_value(env, "DEBUG", "True")

    content = f'''# Generated by scripts/generate_utils.py -- do not edit by hand.
from pathlib import Path

_project_root = Path(__file__).resolve().parents[2]

openai_api_key = {api_key!r}
openai_api_base = {base_url!r}
openai_model = {model!r}
openai_completion_model = {completion_model!r}
llm_disable_embeddings = {disable_embeddings!r}
openai_embedding_model = {embedding_model!r}
key_owner = {key_owner!r}

maze_assets_loc = str(_project_root / "backend" / "static" / "assets")
env_matrix = f"{{maze_assets_loc}}/the_ville/matrix"
env_visuals = f"{{maze_assets_loc}}/the_ville/visuals"

fs_storage = str(_project_root / "data" / "storage")
fs_temp_storage = str(_project_root / "data" / "temp_storage")

collision_block_id = "32125"

debug = {debug}
'''
    OUT.write_text(content)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
