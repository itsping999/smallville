def GPT_request(prompt, gpt_parameter):
    temp_sleep()
    try:
        # Most custom providers expose chat completions, even when the
        # original prompt function asks for legacy text completions.
        # Use chat completions by default; set LLM_USE_LEGACY_COMPLETIONS=1
        # to opt back into Completion.create.
        if os.getenv("LLM_USE_LEGACY_COMPLETIONS", "0") == "1":
            response = openai.Completion.create(
                model=COMPLETION_MODEL,
                prompt=prompt,
                temperature=gpt_parameter["temperature"],
                max_tokens=gpt_parameter["max_tokens"],
                top_p=gpt_parameter["top_p"],
                frequency_penalty=gpt_parameter["frequency_penalty"],
                presence_penalty=gpt_parameter["presence_penalty"],
                stream=gpt_parameter["stream"],
                stop=gpt_parameter["stop"],
            )
            return response.choices[0].text
        return _chat_completion(
            prompt,
            model=COMPLETION_MODEL,
            temperature=gpt_parameter.get("temperature"),
            max_tokens=gpt_parameter.get("max_tokens"),
            top_p=gpt_parameter.get("top_p"),
            stop=gpt_parameter.get("stop"),
        )
    except:
        print("TOKEN LIMIT EXCEEDED")
        return "TOKEN LIMIT EXCEEDED"


def generate_prompt(curr_input, prompt_lib_file):
    if type(curr_input) == type("string"):
        curr_input = [curr_input]
    curr_input = [str(i) for i in curr_input]

    f = open(prompt_lib_file, "r")
    prompt = f.read()
    f.close()
    for count, i in enumerate(curr_input):
        prompt = prompt.replace(f"!<INPUT {count}>!", i)
    if "<commentblockmarker>###</commentblockmarker>" in prompt:
        prompt = prompt.split("<commentblockmarker>###</commentblockmarker>")[1]
    return prompt.strip()


def safe_generate_response(prompt,
                           gpt_parameter,
                           repeat=5,
                           fail_safe_response="error",
                           func_validate=None,
                           func_clean_up=None,
                           verbose=False):
    if verbose:
        print(prompt)

    for i in range(repeat):
        curr_gpt_response = GPT_request(prompt, gpt_parameter)
        if func_validate(curr_gpt_response, prompt=prompt):
            return func_clean_up(curr_gpt_response, prompt=prompt)
        if verbose:
            print("---- repeat count: ", i, curr_gpt_response)
            print(curr_gpt_response)
            print("~~~~")
    return fail_safe_response


def get_embedding(text, model=None):
    text = text.replace("\n", " ")
    if not text:
        text = "this is blank"
    if _embeddings_disabled():
        rng = random.Random(text)
        return [rng.uniform(-1, 1) for _ in range(1536)]
    model = _require_provider_config(
        model or EMBEDDING_MODEL, "embedding", "LLM_EMBEDDING_MODEL"
    )
    return openai.Embedding.create(
        input=[text], model=model
    )['data'][0]['embedding']
