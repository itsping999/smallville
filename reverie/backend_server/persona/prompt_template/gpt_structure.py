# Provider configuration: env vars take precedence over generated utils.py.
openai.api_key = os.getenv("LLM_API_KEY", globals().get("openai_api_key", ""))
openai.api_base = os.getenv("LLM_BASE_URL", globals().get("openai_api_base", ""))
CHAT_MODEL = os.getenv("LLM_MODEL", globals().get("openai_model", ""))
COMPLETION_MODEL = os.getenv(
    "LLM_COMPLETION_MODEL",
    globals().get("openai_completion_model", CHAT_MODEL),
)
EMBEDDING_MODEL = os.getenv(
    "LLM_EMBEDDING_MODEL",
    globals().get("openai_embedding_model", ""),
)


def _provider_base_url():
    return os.getenv("LLM_BASE_URL", globals().get("openai_api_base", ""))


def _require_provider_config(model, purpose, model_env="LLM_MODEL"):
    if not _provider_base_url():
        raise RuntimeError(
            f"LLM_BASE_URL is required for {purpose}. "
            "Configure .env and run scripts/generate_utils.py."
        )
    if not model:
        raise RuntimeError(
            f"{model_env} is required for {purpose}. "
            "Configure .env and run scripts/generate_utils.py."
        )
    return model


def _embeddings_disabled():
    raw = os.getenv(
        "LLM_DISABLE_EMBEDDINGS",
        globals().get("llm_disable_embeddings", "0"),
    )
    return str(raw).lower() in ("1", "true", "yes", "on")


def temp_sleep(seconds=0.1):
    time.sleep(seconds)


def _chat_completion(prompt, model=None, temperature=None,
                     max_tokens=None, top_p=None, stop=None):
    model = _require_provider_config(model or CHAT_MODEL, "chat completion")
    system_msg = (
        "You are a text-completion engine. The user message is a partial text. "
        "Continue it naturally with ONLY the next few words. Do NOT repeat, explain, or add anything extra."
    )
    kwargs = {
        "model": model,
        "messages": [
            {"role": "system", "content": system_msg},
            {"role": "user", "content": prompt},
        ],
    }
    if temperature is not None:
        kwargs["temperature"] = temperature
    if max_tokens is not None:
        kwargs["max_tokens"] = max_tokens
    if top_p is not None:
        kwargs["top_p"] = top_p
    if stop is not None:
        kwargs["stop"] = stop
    completion = openai.ChatCompletion.create(**kwargs)
    return completion["choices"][0]["message"]["content"]


def ChatGPT_single_request(prompt):
    temp_sleep()
    return _chat_completion(prompt)


